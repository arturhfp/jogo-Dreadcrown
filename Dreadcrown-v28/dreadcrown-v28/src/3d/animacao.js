/* =====================================================================
   Linha do tempo das animações (keyframes)
   ---------------------------------------------------------------------
   RESPONSABILIDADE: Define o formato da pose (newPose), a interpolação suave entre keyframes (track) e o catálogo ACTIONS: cada ação (golpe, salto, magia, tiro, esquiva, morte…) é uma duração + instantes de impacto (hit) + canais (x, lean, twist, armR, legF, squash…).
   RELAÇÃO COM OUTROS MÓDULOS: Usa só util.js. É lido por atores.js (Actor.update) e combate3d.js.
   API PÚBLICA: newPose, track(keys, t), ACTIONS.
   REGRAS / CUIDADOS: Os instantes em "hit" disparam os efeitos e o dano visual; mudar o tempo de um hit muda a sincronia com o efeito e com a puxada do arco (ver arco.js).
   ===================================================================== */


/* keyframes suaves */
function track(keys, t) {
  if (t <= keys[0][0]) return keys[0][1];
  for (let i = 1; i < keys.length; i++) {
    const a = keys[i - 1], b = keys[i];
    if (t <= b[0]) { let u = (t - a[0]) / (b[0] - a[0]); u = u * u * (3 - 2 * u); return a[1] + (b[1] - a[1]) * u; }
  }
  return keys[keys.length - 1][1];
}

